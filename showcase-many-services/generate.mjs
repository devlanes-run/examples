// Writes devlanes.yaml with the index plus count - 1 services, dealt in turn to
// the api, web, worker and job templates. Usage: node generate.mjs [count]
import { writeFileSync } from "node:fs";

const count = Number(process.argv[2] ?? 40);
if (!Number.isInteger(count) || count < 2) {
  console.error(`count must be a whole number of at least 2, got ${process.argv[2]}`);
  process.exit(1);
}

const kinds = ["api", "web", "worker", "job"];
const width = String(Math.ceil((count - 1) / kinds.length)).length;
const services = [{ name: "index", kind: "web", host: "${{ lane.domain }}" }];
for (let i = 0; i < count - 1; i++) {
  const kind = kinds[i % kinds.length];
  const n = String(Math.floor(i / kinds.length) + 1).padStart(Math.max(2, width), "0");
  services.push({ name: `${kind}-${n}`, kind });
}
// The first api and web service also get a hostname; the rest are port-only.
for (const kind of ["api", "web"]) {
  const first = services.find((s) => s.kind === kind && !s.host);
  if (first) first.host = `${first.name}.\${{ lane.domain }}`;
}

const key = (name) => name.replace(/-/g, "_");
const envName = (name) => name.toUpperCase().replace(/[^A-Z0-9]/g, "_");

const service = (s) => {
  const lines = [`  ${s.name}:`, `    extends: ${s.kind}`];
  if (s.host) lines.push(`    hosts: "${s.host}"`);
  if (s.name !== "index") return lines.join("\n");
  lines.push(
    "    env:",
    "      PAGE: index",
    "      # The index asks every service for /stats on each page load.",
    `      SERVICES: ${services.map((t) => t.name).join(",")}`,
    ...services.map((t) => `      URL_${envName(t.name)}: \${{ services.${key(t.name)}.url }}`),
    ...services
      .filter((t) => t.host)
      .map((t) => `      PUBLIC_URL_${envName(t.name)}: \${{ services.${key(t.name)}.public_url }}`),
  );
  return lines.join("\n");
};

const yaml = `# yaml-language-server: $schema=https://devlanes.run/v1/schema.json
# Generated by generate.mjs (${count} services). Edit generate.mjs or run
# \`node generate.mjs <count>\` instead of editing this file.
project: many-services

global_env:
  LANE_LABEL: \${{ lane.label }}
  LANE_DOMAIN: \${{ lane.domain }}

# A service takes the colour of its first tag that has one, so the TUI and the
# monitor show each category in its own colour.
tags:
  api: { color: cyan, description: JSON APIs }
  web: { color: green, description: Pages }
  worker: { color: magenta, description: Workers that handle a batch every few seconds }
  job: { color: yellow, description: Jobs that run a longer task now and then }

# Every service runs server.mjs. BOOT_MS is how long it works before it
# listens, BURST_MS how long each CPU burst lasts and BURST_EVERY_MS the pause
# between bursts; each is a min-max range in milliseconds, picked at random.
templates:
  node:
    # node itself rather than an npm script: npm would add a second Node
    # process to each of the ${count} services.
    run: [node, server.mjs]
    cwd: .
    env:
      BOOT_MS: 1000-6000
  api:
    extends: node
    tags: [api]
    # Each service holds its start slot until its ready check passes.
    ready:
      http:
        path: /healthz
    env:
      KIND: api
      BURST_MS: 30-120
      BURST_EVERY_MS: 2000-5000
  web:
    extends: node
    tags: [web]
    ready:
      http:
        path: /healthz
    env:
      KIND: web
      BURST_MS: 20-80
      BURST_EVERY_MS: 3000-6000
  worker:
    extends: node
    tags: [worker]
    # No page to probe: the start waits for this line instead.
    ready:
      log: "ready after"
    env:
      KIND: worker
      BURST_MS: 100-300
      BURST_EVERY_MS: 4000-8000
  job:
    extends: node
    tags: [job]
    ready:
      log: "ready after"
    env:
      KIND: job
      BURST_MS: 300-800
      BURST_EVERY_MS: 10000-20000

services:
${services.map(service).join("\n")}
`;

writeFileSync(new URL("./devlanes.yaml", import.meta.url), yaml);
console.log(`wrote devlanes.yaml with ${services.length} services`);
