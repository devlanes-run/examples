// Writes devlanes.yaml: scripts/base.yaml plus the index and count - 1 services,
// dealt in turn to the api, web, worker and job templates.
// Usage: node scripts/generate.ts [count]
import { readFileSync, writeFileSync } from "node:fs";

const KINDS = ["api", "web", "worker", "job"] as const;
const DEFAULT_COUNT = 40;

type Service = { name: string; kind: (typeof KINDS)[number]; host?: string };

function parseCount(arg: string | undefined): number {
  const count = Number(arg ?? DEFAULT_COUNT);
  if (!Number.isInteger(count) || count < 2) {
    console.error(`count must be a whole number of at least 2, got ${arg}`);
    process.exit(1);
  }
  return count;
}

/** The index first, then api-01, web-01, worker-01, job-01, api-02 and so on. */
function planServices(count: number): Service[] {
  const width = Math.max(2, String(Math.ceil((count - 1) / KINDS.length)).length);
  const services: Service[] = [{ name: "index", kind: "web", host: "${{ lane.domain }}" }];
  for (let i = 0; i < count - 1; i++) {
    const kind = KINDS[i % KINDS.length];
    const n = String(Math.floor(i / KINDS.length) + 1).padStart(width, "0");
    services.push({ name: `${kind}-${n}`, kind });
  }
  // The first api and web service also get a hostname; the rest are port-only.
  for (const kind of ["api", "web"]) {
    const first = services.find((s) => s.kind === kind && !s.host);
    if (first) first.host = `${first.name}.\${{ lane.domain }}`;
  }
  return services;
}

/** `api-01` as an expression key (`api_01`) and as part of a variable name (`API_01`). */
const exprKey = (name: string) => name.replace(/-/g, "_");
const envKey = (name: string) => name.toUpperCase().replace(/[^A-Z0-9]/g, "_");

/** The index's env: the list of services and the URLs it fetches and links to. */
function indexEnv(services: Service[]): string[] {
  return [
    "    env:",
    "      PAGE: index",
    "      # The index asks every service for /stats on each page load.",
    `      SERVICES: ${services.map((s) => s.name).join(",")}`,
    ...services.map((s) => `      URL_${envKey(s.name)}: \${{ services.${exprKey(s.name)}.url }}`),
    ...services
      .filter((s) => s.host)
      .map(
        (s) => `      PUBLIC_URL_${envKey(s.name)}: \${{ services.${exprKey(s.name)}.public_url }}`,
      ),
  ];
}

function renderService(service: Service, all: Service[]): string {
  const lines = [`  ${service.name}:`, `    extends: ${service.kind}`];
  if (service.host) lines.push(`    hosts: "${service.host}"`);
  if (service.name === "index") lines.push(...indexEnv(all));
  return lines.join("\n");
}

function main(): void {
  const count = parseCount(process.argv[2]);
  const services = planServices(count);
  const base = readFileSync(new URL("./base.yaml", import.meta.url), "utf8");
  const yaml = [
    "# yaml-language-server: $schema=https://devlanes.run/v1/schema.json",
    `# Generated by scripts/generate.ts from scripts/base.yaml (${count} services).`,
    "# Edit those or run `node scripts/generate.ts <count>` instead of editing this file.",
    base.trimEnd(),
    "",
    "services:",
    ...services.map((s) => renderService(s, services)),
    "",
  ].join("\n");
  writeFileSync(new URL("../devlanes.yaml", import.meta.url), yaml);
  console.log(`wrote devlanes.yaml with ${services.length} services`);
}

main();
